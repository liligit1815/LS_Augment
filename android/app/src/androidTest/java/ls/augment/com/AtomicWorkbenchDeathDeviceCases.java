        main(() -> { View tile = activity.getWindow().getDecorView().findViewWithTag("atomic-workbench-quick-app:" + component);
            require(tile.isEnabled() && tile.performClick(), "REAL_TILE_CLICK"); return null; });
        AtomicReference<Bundle> accepted = new AtomicReference<>();
        await(() -> {
            int id = main(() -> ((AtomicWorkbenchWorkspaceModel) field("model")).mainWindowId());
            for (Bundle value : windows(status())) if (value.getInt("window_id", -1) == id) {
                ArrayList<String> running = value.getStringArrayList("running_packages");
                if (value.getBoolean("success") && !value.getBoolean("recovery_pending")
                        && "active".equals(value.getString("state")) && component.equals(value.getString("top_component"))
                        && running != null && running.contains(pkg) && value.getInt("display_id", -1) > 0
                        && value.getInt("task_id", -1) > 0 && main(() -> (Boolean) invoke("mainReady"))) {
                    accepted.set(new Bundle(value)); return true;
                }
            }
            return false;
        }, "ACTUAL_MAIN_AND_TASK");
        Bundle window = accepted.get();
        Bundle fixture = awaitFixture(pkg, value -> !value.getBoolean("destroyed") && value.getLong("at_uptime") >= attempted
                && value.getInt("task_id") == window.getInt("task_id") && value.getInt("display_id") == window.getInt("display_id"));
