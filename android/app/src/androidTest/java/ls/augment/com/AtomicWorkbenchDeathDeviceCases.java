    private JSONObject observeIndependent(long instrumentationCreatedUptime) throws Exception {
        // HOST is after-the-fact only. AMS/Application startup precedes this code:
        // the operator must seal the entire system-only automatic window BEFORE
        // launching this instrumentation. This check cannot undo an early launch.
        setup = read("setup.json"); requireBase(setup);
        JSONObject outcome;
        boolean afterWindowAuthorized = false;
        try {
            prepared = read("prepared.json"); requireBase(prepared);
            require(sha(new File(directory, "setup.json")).equals(prepared.getString("setupSha256")), "SETUP_IDENTITY");
            JSONObject oldHost = prepared.getJSONObject("processes").getJSONObject("host");
            JSONObject now = selfIdentity();
            require(oldHost.getInt("uid") == Process.myUid()
                    && (oldHost.getInt("pid") != Process.myPid()
                        || !oldHost.getString("startTicks").equals(now.getString("startTicks"))), "HOST_NOT_REPLACED");
            JSONObject receipt = read("death-receipt.json"); validateReceipt(receipt);
            long deadline = receipt.getLong("killRequestedUptime") + OBSERVE_MS;
            require(instrumentationCreatedUptime > deadline
                    && instrumentationCreatedUptime <= SystemClock.uptimeMillis(), "HOST_OBSERVER_STARTED_WITHIN_AUTOMATIC_WINDOW");
            afterWindowAuthorized = true;
            outcome = observeHostAfterFact(receipt, instrumentationCreatedUptime);
            writeNew("after-fact-host-observation.json", outcome);
        } catch (Throwable failure) {
            outcome = base().put("phase", "HOST_AFTER_FACT_UNCONFIRMED")
                    .put("success", false).put("automaticRecoveryConfirmed", false)
                    .put("automaticWindowObservationPerformed", false)
                    .put("instrumentationCreatedUptime", instrumentationCreatedUptime)
                    .put("afterWindowAuthorized", afterWindowAuthorized)
                    .put("failureType", failure.getClass().getName());
            writeNew("unconfirmed-observer.json", outcome);
        } finally {
            JSONObject recovery = new JSONObject();
            try {
                recovery = base().put("phase", "HOST_OBSERVER_FINALLY")
                        .put("afterWindowAuthorized", afterWindowAuthorized);
            } finally {
                try { if (registered) target.unregisterReceiver(receiver); recovery.put("receiverReleased", true); }
                catch (Throwable error) { recovery.put("receiverReleased", false).put("receiverErrorType", error.getClass().getName()); }
                // An early/malformed observer must not write configuration during
                // the automatic window. The operator retains quick responsibility.
                if (afterWindowAuthorized) {
                    try { saveQuick(setup.getString("originalQuick")); recovery.put("quickRestoreAttempted", true).put("quickRestored", true); }
                    catch (Throwable error) { recovery.put("quickRestoreAttempted", true).put("quickRestored", false).put("quickErrorType", error.getClass().getName()); }
                } else recovery.put("quickRestoreAttempted", false).put("quickRestored", false);
            }
            writeNew("observer-finally.json", recovery);
        }
        return outcome.put("observerFinishingAfterAutomaticDeadline", afterWindowAuthorized)
                .put("externalAutomaticEvidenceSealVerifiedByThisEntry", false)
                .put("finishMayForceStopHostPackage", true);
    }

