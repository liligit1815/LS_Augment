    private final BroadcastReceiver receiver = new BroadcastReceiver() {
        @Override public void onReceive(Context context, Intent intent) {
            if (intent == null || !AtomicWorkbenchFixtureActivity.ACTION_STATE.equals(intent.getAction())
                    || !nonce.equals(intent.getStringExtra("nonce"))) return;
            String pkg = intent.getStringExtra("fixture_package");
            Integer uid = uids.get(pkg);
            Bundle value = intent.getExtras();
            if (uid == null || getSentFromUid() != uid || value == null
                    || !(value.get("fixture_protocol") instanceof Integer)
                    || value.getInt("fixture_protocol") != 5
                    || !(value.get("task_id") instanceof Integer)
                    || !(value.get("display_id") instanceof Integer)
                    || !(value.get("at_uptime") instanceof Long)
                    || !(value.get("destroyed") instanceof Boolean)) return;
            synchronized (observationLock) {
                Bundle previous = observations.get(pkg);
                if (previous != null && previous.getLong("at_uptime") >= value.getLong("at_uptime")) return;
                observations.put(pkg, new Bundle(value));
                if (prepared != null) try {
                    int task = fixture(prepared, pkg).getInt("task_id");
                    if (value.getInt("task_id") != task && identityConflicts.length() < 16)
                        identityConflicts.put(new JSONObject().put("package", pkg)
                                .put("expectedTask", task).put("observedTask", value.getInt("task_id"))
                                .put("at_uptime", value.getLong("at_uptime")));
                } catch (Exception malformed) { identityConflicts.put("PREPARED_IDENTITY_UNREADABLE"); }
            }
        }
    };

