    private JSONObject heldDurableProof(Bundle entry, AtomicWorkbenchTaskIdentity original,
                                        AtomicWorkbenchTaskUiSnapshot.Window source) throws Exception {
        // Before death only. Actual Store reader takes its disk-only lock and never invokes Binder.
        File file = new File(target.getFilesDir(), "atomic_workbench/task-shelf.json");
        require(file.isFile(), "HELD_STORE_FILE_MISSING");
        AtomicWorkbenchTaskShelfStore.Snapshot snapshot = new AtomicWorkbenchTaskShelfStore(target,
                Process.myUid(), Process.myUid() / 100000).read();
        require(snapshot.revision == AtomicWorkbenchTaskIdentity.number(entry, "revision"), "HELD_STORE_REVISION");
        AtomicWorkbenchTaskShelfStore.Record found = null;
        for (AtomicWorkbenchTaskShelfStore.Record record : snapshot.records)
            if (record.shelfId.equals(entry.getString("shelf_id"))) { require(found == null, "HELD_STORE_DUPLICATE"); found = record; }
        require(found != null && found.metadata.action == AtomicWorkbenchTaskOperationRequest.Action.SHELVE
                && found.phase == AtomicWorkbenchTaskShelfStore.Phase.COMMITTED
                && found.disposition == AtomicWorkbenchTaskShelfStore.Disposition.SHELVED_REFERENCE
                && found.leaseState == AtomicWorkbenchTaskShelfStore.LeaseState.HELD && !found.pending()
                && found.previous == null && found.operationId.equals(entry.getString("operation_id"))
                && found.leaseId.equals(entry.getString("lease_id")) && found.metadata.identity.equals(original)
                && found.metadata.sourceSlot == source.id && found.metadata.sourceWindowSession.equals(source.session)
                && found.observedIdentity != null && found.observedIdentity.equals(AtomicWorkbenchTaskIdentity.fromBundle(entry.getBundle("identity"))), "HELD_STORE_UNCONFIRMED");
        File journal = new File(target.getFilesDir(), "atomic_workbench/recovery-window-" + source.id + ".json");
        String firstHash = sha(journal);
        AtomicWorkbenchJournal.Record owner = AtomicWorkbenchJournal.Record.fromJson(new JSONObject(text(journal, 256 * 1024)));
        require(firstHash.equals(sha(journal)) && owner.ownerUid == Process.myUid() && owner.userId == original.userId
                && owner.windowId == source.id && owner.session.equals(source.session) && owner.displayId == source.displayId
                && owner.displayName.equals(source.name) && owner.uniqueId.equals(source.unique), "HELD_JOURNAL_IDENTITY");
        boolean acknowledged = false;
        for (AtomicWorkbenchJournal.TaskOrigin origin : owner.tasks)
            if (origin.serverBootGeneration.equals(original.serverBootGeneration) && origin.taskGeneration.equals(original.taskGeneration)) {
                require(!acknowledged && origin.taskId == original.taskId && origin.uid == original.uid && origin.userId == original.userId
                        && origin.component.equals(original.baseComponent) && "SHELVED_REFERENCE".equals(origin.disposition)
                        && origin.successorSession.isEmpty(), "HELD_JOURNAL_HANDOFF"); acknowledged = true;
            }
        require(acknowledged, "HELD_JOURNAL_HANDOFF_MISSING");
        for (AtomicWorkbenchJournal.TaskOperation operation : owner.taskOperations)
            require(!operation.operationId.equals(found.operationId), "HELD_JOURNAL_OPERATION_PENDING");
        return new JSONObject().put("storeSchema", snapshot.storageSchema).put("storeEpoch", snapshot.storeEpoch)
                .put("storeRevision", snapshot.revision).put("record", found.json()).put("sourceJournalSha256", firstHash);
    }

