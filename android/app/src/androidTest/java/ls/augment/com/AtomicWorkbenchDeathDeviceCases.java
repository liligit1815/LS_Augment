    private static JSONObject shelfFingerprints(Bundle state, String excluded) throws Exception {
        java.util.TreeMap<String, String> rows = new java.util.TreeMap<>();
        for (Bundle row : shelfRows(state)) {
            String id = AtomicWorkbenchTaskIdentity.string(row, "shelf_id");
            if (id.equals(excluded)) continue;
            Bundle stable = new Bundle(row); stable.remove("revision");
            // Entries reflect live inspection. A changed unrelated fact is a changed scope, not silently accepted.
            require(rows.put(id, shaText(json(stable).toString())) == null, "HELD_SHELF_DUPLICATE");
        }
        return new JSONObject(rows);
    }
    private static JSONObject json(Bundle value) throws Exception {
        JSONObject result = new JSONObject();
        for (String key : new java.util.TreeSet<>(value.keySet())) {
            Object item = value.get(key); result.put(key, item instanceof Bundle ? json((Bundle) item) : item);
        }
        return result;
    }
    private static Bundle bundle(JSONObject value) throws Exception {
        Bundle result = new Bundle(); java.util.Iterator<String> keys = value.keys();
        while (keys.hasNext()) {
            String key = keys.next(); Object item = value.get(key);
            if (item instanceof Integer) result.putInt(key, (Integer) item);
            else if (item instanceof Long) result.putLong(key, (Long) item);
            else if (item instanceof Boolean) result.putBoolean(key, (Boolean) item);
            else if (item instanceof String) result.putString(key, (String) item);
            else if (item instanceof JSONObject) result.putBundle(key, bundle((JSONObject) item));
            else throw new AssertionError("HELD_JSON_TYPE");
        }
        return result;
    }
    private static String shaText(String text) throws Exception {
        byte[] digest = MessageDigest.getInstance("SHA-256").digest(text.getBytes(StandardCharsets.UTF_8));
        StringBuilder result = new StringBuilder(); for (byte value : digest) result.append(String.format(java.util.Locale.ROOT, "%02X", value & 255));
        return result.toString();
    }

